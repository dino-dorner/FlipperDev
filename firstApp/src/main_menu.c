/** main menu callback - sends a custom event to the scene manager based on the menu selection */
void stock_app_menu_callback_main_menu(void* context, uint32_t index) {
    FURI_LOG_T(TAG, "stock_app_menu_callback_main_menu");

    //casting app
    StockTrackerApp* app = context;
    switch(index) {
    case Menu_TickerSelect:
        scene_manager_handle_custom_event(app->scene_manager, stockTracker_ShowTickerSelect);
        break;
    case Menu_TickerOverview:
        scene_manager_handle_custom_event(app->scene_manager, stockTracker_ShowTickerOverview);
        break;
    case Menu_TickerDelete:
        scene_manager_handle_custom_event(app->scene_manager, stockTracker_ShowTickerDelete);
        break;
    case Menu_Wifi:
        scene_manager_handle_custom_event(app->scene_manager, stockTracker_ShowWifi);
        break;
    }
    
}

/** resets the menu, gives it content, callbacks and selection enums */
void stock_app_scene_on_enter_main_menu(void* context) {
    FURI_LOG_T(TAG, "test_app_scene_on_enter_main_menu");
    StockTrackerApp* app = context;
    menu_reset(app->menu);

    // NB. icons are specified as NULL below, because:
    // * icons are _always_ animated by the menu
    // * the icons provided (&I_one, &I_two) are generated by the build process
    // * these icons do not have a framerate (resulting in a division by zero)
    menu_add_item(
        app->menu,
        "Enter Stock Ticker",
        NULL,
        Menu_TickerSelect,
        stock_app_menu_callback_main_menu,
        app);
    menu_add_item(
        app->menu,
        "Ticker Overview",
        NULL,
        Menu_TickerOverview,
        stock_app_menu_callback_main_menu,
        app);
    menu_add_item(
        app->menu,
        "Delete Stock Ticker",
        NULL,
        Menu_TickerDelete,
        stock_app_menu_callback_main_menu,
        app
    );
    menu_add_item(
        app->menu,
        "Wifi Setup",
        NULL,
        Wifi,
        stock_app_menu_callback_main_menu,
        app
    );
    view_dispatcher_switch_to_view(app->view_dispatcher, stockTrackerView_Main);
}

/** main menu event handler - switches scene based on the event */
bool stock_app_scene_on_event_main_menu(void* context, SceneManagerEvent event) {
    FURI_LOG_T(TAG, "test_app_scene_on_event_main_menu");
    StockTrackerApp* app = context;
    bool consumed = false;

    switch(event.type) {
        case SceneManagerEventTypeCustom:
            switch(event.event) {
            case stockTracker_ShowTickerSelect:
                scene_manager_next_scene(app->scene_manager, stockTrackerScene_TickerSelect);
                consumed = true;
                break;
            case stockTracker_ShowTickerOverview:
                scene_manager_next_scene(app->scene_manager, stockTrackerScene_TickerScreen);
                consumed = true;
                break;
            case stockTracker_ShowTickerDelete:
                scene_manager_next_scene(app->scene_manager, stockTrackerScene_TickerDelete);
                consumed = true;
                break;
            case stockTracker_ShowWifi:
                scene_manager_next_scene(app->scene_manager, stockTrackerScene_Wifi);
                consumed = true;
                break;
            }
            break;
        default: // eg. SceneManagerEventTypeBack, SceneManagerEventTypeTick. What is this #TODO.
            consumed = false;
            break;
    }
    return consumed;
}

void stock_app_scene_on_exit_main_menu(void* context) {
    FURI_LOG_T(TAG, "stock_app_scene_on_exit_main_menu");
    StockTrackerApp* app = context;
    menu_reset(app->menu);
}